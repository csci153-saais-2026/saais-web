import type { FacultyDepartmentReport } from "@/routes/dean/types"

const MAX_LINE_WIDTH = 86

function sanitizePdfAscii(text: string): string {
  return text
    .replace(/[–—]/g, "-")
    .replace(/[^\x20-\x7E]/g, " ")
}

function escapePdfString(text: string): string {
  return sanitizePdfAscii(text)
    .replace(/\\/g, "\\\\")
    .replace(/\(/g, "\\(")
    .replace(/\)/g, "\\)")
}

function padRight(text: string, width: number): string {
  const clean = sanitizePdfAscii(text)
  if (clean.length >= width) return clean.slice(0, width)
  return clean + " ".repeat(width - clean.length)
}

/**
 * Formats a faculty report into fixed-width printable lines matching the mockup PDF layout.
 */
export function buildFacultyReportPdfLines(
  report: FacultyDepartmentReport,
  generatedBy = "Dr. Paz Villanueva",
): string[] {
  const scope =
    report.department === "All departments"
      ? "Faculty of Computing | All departments | read-only"
      : `Faculty of Computing | ${report.department} | read-only`

  const lines: string[] = [
    "SAAIS - Office of the Dean | Faculty Reports",
    scope,
    `Generated by: ${generatedBy}`,
    "-".repeat(MAX_LINE_WIDTH),
    "",
    "SUMMARY METRICS",
    `  Students:          ${report.students}`,
    `  Mean GWA:          ${report.meanGwa}`,
    `  With deficiencies: ${report.withDeficiencies}`,
    "",
    "FINAL GRADE DISTRIBUTION",
    `  ${padRight("Grade range", 24)} ${padRight("Share of final grades", 24)}`,
    `  ${"-".repeat(48)}`,
    ...report.bands.map(
      (band) => `  ${padRight(band.label, 24)} ${band.percent}%`,
    ),
    "",
    "GWA BY BATCH AND CURRICULUM VERSION",
    `  ${padRight("Batch", 10)} ${padRight("Curriculum", 26)} ${padRight("Students", 12)} Mean GWA`,
    `  ${"-".repeat(60)}`,
    ...report.batchRows.map(
      (row) =>
        `  ${padRight(row.batch, 10)} ${padRight(row.curriculum, 26)} ${padRight(String(row.students), 12)} ${row.meanGwa}`,
    ),
    "",
    "-".repeat(MAX_LINE_WIDTH),
    "Fictional sample records | Reference date: 28 October 2026",
  ]

  return lines
}

/**
 * Computes the export filename matching the mockup naming convention.
 */
export function buildFacultyReportFilename(department: FacultyDepartmentReport["department"]): string {
  if (department === "All departments") {
    return "SAAIS-faculty-reports.pdf"
  }
  const slug = department.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "")
  return `SAAIS-faculty-reports-${slug}.pdf`
}

/**
 * Generates a valid single-page PDF 1.4 document as a Uint8Array using Helvetica / Courier.
 */
export function generateFacultyReportPdfBytes(
  report: FacultyDepartmentReport,
  generatedBy = "Dr. Paz Villanueva",
): Uint8Array {
  const lines = buildFacultyReportPdfLines(report, generatedBy)

  const streamOps = [
    "BT",
    "/F1 10 Tf",
    "48 748 Td",
    "14 TL",
    ...lines.map((line, index) =>
      index === 0 ? `(${escapePdfString(line)}) Tj` : `T* (${escapePdfString(line)}) Tj`,
    ),
    "ET",
  ].join("\n")

  const objects: string[] = [
    "1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n",
    "2 0 obj\n<< /Type /Pages /Kids [3 0 R] /Count 1 >>\nendobj\n",
    "3 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>\nendobj\n",
    `4 0 obj\n<< /Length ${streamOps.length} >>\nstream\n${streamOps}\nendstream\nendobj\n`,
    "5 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Courier >>\nendobj\n",
  ]

  let pdf = "%PDF-1.4\n"
  const offsets: number[] = [0]

  for (const obj of objects) {
    offsets.push(pdf.length)
    pdf += obj
  }

  const xrefStart = pdf.length
  pdf += `xref\n0 ${objects.length + 1}\n`
  pdf += "0000000000 65535 f \n"
  for (let i = 1; i < offsets.length; i++) {
    pdf += `${String(offsets[i]).padStart(10, "0")} 00000 n \n`
  }

  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefStart}\n%%EOF\n`

  return new TextEncoder().encode(pdf)
}

/**
 * Triggers a browser download of the generated faculty report PDF.
 */
export function downloadFacultyReportPdf(
  report: FacultyDepartmentReport,
  generatedBy = "Dr. Paz Villanueva",
): string {
  const filename = buildFacultyReportFilename(report.department)
  const bytes = generateFacultyReportPdfBytes(report, generatedBy)
  const blob = new Blob([bytes.buffer as ArrayBuffer], { type: "application/pdf" })
  const url = URL.createObjectURL(blob)

  const link = document.createElement("a")
  link.href = url
  link.download = filename
  document.body.appendChild(link)
  link.click()
  document.body.removeChild(link)
  URL.revokeObjectURL(url)

  return filename
}

