do $$declare term uuid; department uuid; other uuid; result jsonb;
begin
  select (value->>'id')::uuid into term from test.records where name='school_term';
  select (value->>'id')::uuid into department from test.records where name='department';
  select (value->>'id')::uuid into other from test.records where name='department_b';
  perform test.login(2);
  perform test.expect('PT403','closeSchoolTermEncoding',jsonb_build_object('school_term_id',term),'{"scope":"institution"}');
  perform test.expect('PT403','closeSchoolTermEncoding',jsonb_build_object('school_term_id',term),jsonb_build_object('department_id',other));
  perform test.expect('PT403','setSchoolTermOverride',jsonb_build_object('school_term_id',term),'{"enabled":true}');
  perform test.expect('PT403','updateSchoolTerm',jsonb_build_object('id',term),'{"is_locked":true}');
  result:=test.call('closeSchoolTermEncoding',jsonb_build_object('school_term_id',term),'{"closure_note":"Encoding complete"}');
  perform test.assert((result->>'is_locked')::boolean=false,'department closure changed global lock');
  perform test.assert(jsonb_array_length(result->'department_closures')=1,'scoped closure projection');
  perform test.login(1);
  perform test.expect('PT400','closeSchoolTermEncoding',jsonb_build_object('school_term_id',term),'{}');
  result:=test.call('closeSchoolTermEncoding',jsonb_build_object('school_term_id',term),'{"scope":"institution"}');
  perform test.assert((result->>'is_locked')::boolean,'global close');
  perform test.login(3);
  result:=test.call('reopenDepartmentTermEncoding',jsonb_build_object('school_term_id',term),'{}');
  perform test.assert((result->>'is_closed')::boolean=false,'department reopen');
  perform test.assert((select is_locked from public.school_term where id=term),'reopen lifted global lock');
  perform test.expect('PT403','reopenDepartmentTermEncoding',jsonb_build_object('school_term_id',term),'{"scope":"institution"}');
  perform test.login(1);
  result:=test.call('setSchoolTermOverride',jsonb_build_object('school_term_id',term),'{"enabled":true}');
  perform test.assert((result->>'override_flag')::boolean and result->>'override_actor_id'='00000001-0000-4000-8000-000000000000','server-owned override');
  perform test.call('setSchoolTermOverride',jsonb_build_object('school_term_id',term),'{"enabled":false}');
  perform test.login(7);
  perform test.expect('PT403','closeSchoolTermEncoding',jsonb_build_object('school_term_id',term),'{}');
end$$;
