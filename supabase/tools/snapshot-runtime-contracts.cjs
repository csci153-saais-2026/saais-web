const fs = require("node:fs");
const path = require("node:path");
const { execFileSync } = require("node:child_process");
const {
  migration,
  withPinnedContract,
  buildSnapshot: buildCatalogSnapshot,
} = require("./snapshot-contract.cjs");
const {
  buildSnapshot: buildAcademicSnapshot,
} = require("./snapshot-academic-contract.cjs");

function formatSnapshot(snapshot, filename) {
  return execFileSync(
    process.execPath,
    [
      path.resolve("node_modules/prettier/bin/prettier.cjs"),
      "--stdin-filepath",
      filename,
    ],
    { input: JSON.stringify(snapshot, null, 2) + "\n", encoding: "utf8" },
  );
}

function writeRuntimeSnapshots() {
  const { catalog, academic } = withPinnedContract((contract) => ({
    catalog: buildCatalogSnapshot(contract),
    academic: buildAcademicSnapshot(contract),
  }));
  const sql = `-- Generated by supabase/tools/snapshot-runtime-contracts.cjs; do not edit.
with catalog(document) as (
  values ($catalog_contract$${JSON.stringify(catalog)}$catalog_contract$::jsonb)
),
academic(document) as (
  values ($academic_contract$${JSON.stringify(academic)}$academic_contract$::jsonb)
),
updated_catalog as (
  insert into saais_private.contract (id, document)
  select true, jsonb_set(catalog.document, '{schemas}', (catalog.document->'schemas') || (academic.document->'schemas'))
  from catalog cross join academic
  on conflict (id) do update set document = excluded.document
)
insert into saais_private.matt_contract (id, document)
select true, document from academic
on conflict (id) do update set document = excluded.document;
`;
  const catalogPath = "supabase/functions/_shared/contract.json";
  const academicPath = "supabase/functions/_shared/academic-contract.json";
  const catalogJson = formatSnapshot(catalog, catalogPath);
  const academicJson = formatSnapshot(academic, academicPath);
  fs.writeFileSync(catalogPath, catalogJson);
  fs.writeFileSync(academicPath, academicJson);
  fs.writeFileSync(migration, sql);
}

module.exports = { writeRuntimeSnapshots };

if (require.main === module) writeRuntimeSnapshots();
