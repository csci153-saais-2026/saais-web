"""Generate locale-independent Unicode case folding for the outside-credit key.

The generated immutable SQL embeds the Unicode mapping as constants so it can
be indexed on PostgreSQL 17 as well as 18, without a mutable lookup table.
"""
from pathlib import Path
import unicodedata


def quote(value):
    return "'" + value.replace("'", "''") + "'"


mapping = []
for ordinal in range(0x110000):
    character = chr(ordinal)
    if character.casefold() != character:
        mapping.append("(" + quote(character) + "," + quote(character.casefold()) + ")")

sql = "-- Generated by supabase/tools/generate-casefold.py; Unicode " + unicodedata.unidata_version + ". Do not edit.\n"
sql += """create function saais_private.casefold(value text) returns text
language sql immutable strict parallel safe set search_path=pg_catalog as $fold$
  select coalesce(string_agg(coalesce(mapping.folded,chars.character),'' order by chars.ordinal),'')
  from regexp_split_to_table(value,'') with ordinality chars(character,ordinal)
  left join (values
"""
sql += ",\n".join(mapping)
sql += """
  ) mapping(character,folded) on mapping.character=chars.character;
$fold$;
create function saais_private.outside_key(value text) returns text
language sql immutable strict parallel safe set search_path=pg_catalog as $key$
  select saais_private.casefold(btrim(regexp_replace(value,U&'[\\0009-\\000d\\0020\\0085\\00a0\\1680\\2000-\\200a\\2028\\2029\\202f\\205f\\3000]+',' ','g')));
$key$;
drop index public.outside_credit_live_source;
create unique index outside_credit_live_source on public.outside_credit(student_id,saais_private.outside_key(origin_school),saais_private.outside_key(original_course_code)) where revoked_at is null;
revoke all on function saais_private.casefold(text),saais_private.outside_key(text) from public,anon,authenticated;
"""
Path("supabase/migrations/20261112001060_jerome_outside_keys.sql").write_text(sql, encoding="utf-8", newline="\n")
print("Generated", len(mapping), "Unicode case-fold mappings (Unicode", unicodedata.unidata_version + ").")
